function generateMenu(tags, selectedFav) {
    document.getElementById('favorite-screen').style.display = 'none';
    document.getElementById('tag-screen').style.display = 'none';
    
    let menuItems = [];
    if (tags.length === 1) {
        menuItems = db[tags[0]].slice(0, 6);
    } else {
        const favItems = db[selectedFav].slice(0, 3);
        menuItems = [...favItems];
        
        const otherTags = tags.filter(t => t !== selectedFav);
        
        if (otherTags.length > 0) {
            const slotsLeft = 6 - favItems.length;
            const itemsPerTag = Math.floor(slotsLeft / otherTags.length);
            let extraSlots = slotsLeft % otherTags.length;

            otherTags.forEach(tag => {
                let count = itemsPerTag + (extraSlots > 0 ? 1 : 0);
                if (extraSlots > 0) extraSlots--;
                
                const items = db[tag].slice(0, count);
                menuItems = menuItems.concat(items);
            });
        }
    }

    currentMenuItems = menuItems.slice(0, 6);
    renderMenu(currentMenuItems);
    document.getElementById('menu-screen').style.display = 'flex';
}

