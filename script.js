function createMapUrl(data) {
    const base = "https://maps.google.com/maps";
    const zoom = 15;

    if (data.pins && data.pins.length > 0) {
        const markerString = data.pins.map(pin => `${pin.lat},${pin.lng}`).join('|');
        const centerLat = data.lat || data.pins[0].lat;
        const centerLng = data.lng || data.pins[0].lng;
        return `${base}?q=${encodeURIComponent(markerString)}&ll=${centerLat},${centerLng}&z=${zoom}&output=embed`;
    }

    if (data.lat && data.lng) {
        return `${base}?q=${data.lat},${data.lng}&ll=${data.lat},${data.lng}&z=${zoom}&output=embed`;
    }

    const pureName = data.j.replace(/<[^>]*>?/gm, '');
    const searchQuery = encodeURIComponent(`${pureName} 神戸`);
    return `${base}?q=${searchQuery}&z=${zoom}&output=embed`;
}

