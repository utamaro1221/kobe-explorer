    document.getElementById('content-text').innerHTML = currentLang === 'en' ? item.enDesc : formatText(item.descHtml);

    if (leafletMap) {
        leafletMap.remove();
        leafletMap = null;
    }

    leafletMap = L.map('target-map', {
        scrollWheelZoom: false,
        dragging: false,
        touchZoom: false
    });

    leafletMap.once('click', function() {
        leafletMap.scrollWheelZoom.enable();
        leafletMap.dragging.enable();
        leafletMap.touchZoom.enable();
    });

    L.tileLayer('https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png', {
        attribution: '© OpenStreetMap contributors'
    }).addTo(leafletMap);

    let markers = [];
    
    if (item.pins && item.pins.length > 0) {
        item.pins.forEach(pin => {
            const m = L.marker([pin.lat, pin.lng]).addTo(leafletMap);
            markers.push(m);
        });
    } else if (item.lat && item.lng) {
        const m = L.marker([item.lat, item.lng]).addTo(leafletMap);
        markers.push(m);
    }

    if (markers.length > 1) {
        const group = new L.featureGroup(markers);
        leafletMap.fitBounds(group.getBounds(), { padding: [20, 20] });
    } else if (markers.length === 1) {
        leafletMap.setView(markers[0].getLatLng(), 15);
    } else {
        leafletMap.setView([34.6901, 135.1955], 13);
    }

    const linkBox = document.getElementById('link-box');
    const siteLinks = document.getElementById('site-links');
    siteLinks.innerHTML = '';
    const urls = item.urls || (item.url ? [item.url] : []);
    const shouldShowLinks = cat !== 'グルメ' && urls.length > 0;

